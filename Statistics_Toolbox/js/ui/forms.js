// StatLab UI layer (sample-data buttons, accessible labels, copy button, interface observer). Presentation only: no calculation logic lives here.
(function () {
    const { $, $$, showToast, countTools, decorateSidebars, hookCard } = window.StatLabUI;
    function samplesFor(iface) {
        const out = [];
        $$('textarea', iface).forEach(t => {
            const ph = t.getAttribute('placeholder') || '';
            const m = ph.match(/(?:example|e\.g\.)\s*[:\-]?\s*([\s\S]+)/i);
            const val = (m ? m[1] : ph).trim();
            if (/\d/.test(val) && val.length < 700 && (m ? /^[^<>]+$/.test(val) : /^[\d\s,.;\-+eE\n\r]+$/.test(val))) out.push([t, val]);
        });
        return out;
    }
    // Interfaces are generated by many render functions; give them accessible names and live results in one place
    function makeAccessible(iface) {
        $$('.btn-icon', iface).forEach(e => e.setAttribute('aria-hidden', 'true'));
        // Decorative leading emoji ("📐 Arithmetic Mean") would be read out as "triangular ruler": hide them from screen readers
        $$('.interface-title, .result-label, .primary-btn, .secondary-btn, .formula-card .formula, label', iface).forEach(el => {
            const t = el.firstChild;
            if (!t || t.nodeType !== 3) return;
            const m = t.nodeValue.match(/^\s*((?:\p{Extended_Pictographic}\uFE0F?\u200D?)+)\s*/u);
            if (!m) return;
            const span = document.createElement('span');
            span.setAttribute('aria-hidden', 'true'); span.textContent = m[1] + ' ';
            t.nodeValue = t.nodeValue.slice(m[0].length);
            el.insertBefore(span, t);
        });
        $$('label:not([for])', iface).forEach(l => {
            if (l.querySelector('input, select, textarea')) return;
            let n = l.nextElementSibling;
            while (n && !/^(INPUT|SELECT|TEXTAREA)$/.test(n.tagName) && !n.querySelector('input, select, textarea')) n = n.nextElementSibling;
            const ctl = n && (/^(INPUT|SELECT|TEXTAREA)$/.test(n.tagName) ? n : n.querySelector('input, select, textarea'));
            if (!ctl) return;
            if (!ctl.id) ctl.id = (iface.id || 'iface') + '-ctl-' + Math.random().toString(36).slice(2, 8);
            l.htmlFor = ctl.id;
        });
        $$('.result-value', iface).forEach(v => { v.setAttribute('role', 'status'); v.setAttribute('aria-live', 'polite'); });
        $$('button:not([type])', iface).forEach(b => { b.type = 'button'; });
    }
    function enhance(iface) {
        if (iface.dataset.enhanced) return; iface.dataset.enhanced = '1';
        const samples = samplesFor(iface);
        const row = $('.action-row', iface);
        if (row && samples.length) {
            const b = document.createElement('button'); b.type = 'button'; b.className = 'secondary-btn sample-btn'; b.textContent = '✨ Try sample data';
            b.addEventListener('click', () => {
                samples.forEach(([t, v]) => { t.value = v; });
                const go = $('.primary-btn', row); if (go) go.focus();
                showToast('Sample data loaded. Press Calculate.');
            });
            row.insertBefore(b, $('.secondary-btn', row));
        }
        makeAccessible(iface);
        $$('.result-card', iface).forEach(hookCard);
        $$('.result-card', iface).forEach(card => {
            if (card.querySelector('.copy-btn')) return;
            const c = document.createElement('button'); c.type = 'button'; c.className = 'copy-btn'; c.textContent = '⧉ Copy solution';
            c.addEventListener('click', () => {
                const txt = card.innerText.replace('⧉ Copy solution', '').trim();
                const done = () => showToast('Solution copied to clipboard');
                if (navigator.clipboard) navigator.clipboard.writeText(txt).then(done, () => showToast('Copy blocked by browser'));
                else showToast('Copy not available in this browser');
            });
            card.appendChild(c);
        });
    }
    const root = $('#interfaceRoot');
    new MutationObserver(() => $$('.stat-interface', root).forEach(enhance)).observe(root, { childList: true, subtree: true });
    $$('.stat-interface', root).forEach(enhance);

    function init() { decorateSidebars(); countTools(); }
    init();
    window.addEventListener('load', init);
})();
