// StatLab UI layer (sample-data buttons, accessible labels, copy button, interface observer). Presentation only: no calculation logic lives here.
(function () {
    const { $, $$, showToast, countTools, decorateSidebars, hookCard } = window.StatLabUI;
    // Placeholders are written as HTML attribute text ("Example:&#10;1, 2, 3"), so entities that survive into the string
    // (double-escaped markup, or text taken from the source rather than the DOM) are decoded before the sample is used.
    const NAMED_ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', minus: '-', ndash: '-', mdash: '-', hellip: '...' };
    function decodeEntities(text) {
        let out = String(text);
        for (let pass = 0; pass < 2; pass++) {           // twice: "&amp;#10;" becomes "&#10;" and then a newline
            out = out.replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
                     .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
                     .replace(/&([a-z]+);/gi, (m, name) => (name.toLowerCase() in NAMED_ENTITIES ? NAMED_ENTITIES[name.toLowerCase()] : m));
        }
        return out;
    }
    // SAMPLE-DATA CONTRACT (also in README.md): a pasted-data textarea has a placeholder of the form "Example: <data>"; this reads it for the
    // "Try sample data" button. Parameter-only tools (parameterOnly: true in buildInterface) have no textarea. tests/structure.test.js enforces it.
    // Returns the sample text of a placeholder ("Example: 1, 2, 3"), or null when the placeholder offers none
    function sampleFromPlaceholder(placeholder) {
        const ph = decodeEntities(placeholder || '').replace(/\r\n?/g, '\n');
        const m = ph.match(/(?:example|e\.g\.)\s*[:\-]?\s*([\s\S]+)/i);
        const val = (m ? m[1] : ph).trim();
        if (!val || val.length >= 700) return null;
        // An explicit "Example:" may be anything that is not markup (category names like "Red, Apple" have no digits);
        // a placeholder without the marker is used only if it is purely numeric
        if (m ? /^[^<>]+$/.test(val) : /\d/.test(val) && /^[\d\s,.;\-+eE\n]+$/.test(val)) return val;
        return null;
    }
    function samplesFor(iface) {
        const out = [];
        $$('textarea', iface).forEach(t => {
            const val = sampleFromPlaceholder(t.getAttribute('placeholder'));
            if (val !== null) out.push([t, val]);
        });
        return out;
    }
    // Interfaces are generated by many render functions; give them accessible names and live results in one place
    function makeAccessible(iface) {
        $$('.btn-icon', iface).forEach(e => e.setAttribute('aria-hidden', 'true'));
        // Decorative leading emoji ("📐 Arithmetic Mean") would be read out as "triangular ruler": hide them from screen readers
        $$('.interface-title, .result-label, .primary-btn, .secondary-btn, .formula-card .formula, label', iface).forEach(el => {
            const t = el.firstChild;
            if (!t || t.nodeType !== 3) return;
            const m = t.nodeValue.match(/^\s*((?:\p{Extended_Pictographic}\uFE0F?\u200D?)+)\s*/u);
            if (!m) return;
            const span = document.createElement('span');
            span.setAttribute('aria-hidden', 'true'); span.textContent = m[1] + ' ';
            t.nodeValue = t.nodeValue.slice(m[0].length);
            el.insertBefore(span, t);
        });
        $$('label:not([for])', iface).forEach(l => {
            if (l.querySelector('input, select, textarea')) return;
            let n = l.nextElementSibling;
            while (n && !/^(INPUT|SELECT|TEXTAREA)$/.test(n.tagName) && !n.querySelector('input, select, textarea')) n = n.nextElementSibling;
            const ctl = n && (/^(INPUT|SELECT|TEXTAREA)$/.test(n.tagName) ? n : n.querySelector('input, select, textarea'));
            if (!ctl) return;
            if (!ctl.id) ctl.id = (iface.id || 'iface') + '-ctl-' + Math.random().toString(36).slice(2, 8);
            l.htmlFor = ctl.id;
        });
        // The tool title is the page's heading for this tool, and the place keyboard focus moves to when a tool is chosen (see focusToolTitle)
        $$('.interface-title', iface).forEach(t => { t.setAttribute('role', 'heading'); t.setAttribute('aria-level', '2'); t.tabIndex = -1; });
        $$('.result-value', iface).forEach(v => { v.setAttribute('role', 'status'); v.setAttribute('aria-live', 'polite'); });
        // The worked solution is a labelled region that users move to when they want it. It is deliberately NOT a live region:
        // after every calculation the short answer (.result-value, role="status" above) is what gets announced, and a live
        // worked solution would make a screen reader read the whole derivation out.
        $$('.calculation-steps', iface).forEach(v => {
            v.setAttribute('role', 'region'); v.setAttribute('aria-label', 'Worked solution');
        });
        $$('button:not([type])', iface).forEach(b => { b.type = 'button'; });
    }
    // Clipboard API where the page is allowed to use it (secure context + permission); otherwise the old execCommand route
    // through a temporary textarea, which also works when the page is opened from file:// or in an iframe.
    function copyText(text) {
        const legacy = () => {
            const ta = document.createElement('textarea');
            ta.value = text; ta.setAttribute('readonly', ''); ta.setAttribute('aria-hidden', 'true');
            ta.style.cssText = 'position: fixed; top: 0; left: 0; width: 1px; height: 1px; opacity: 0;';
            document.body.appendChild(ta);
            const active = document.activeElement;
            ta.select(); ta.setSelectionRange(0, text.length);
            let ok = false;
            try { ok = document.execCommand('copy'); } catch (e) { ok = false; }
            ta.remove();
            if (active && typeof active.focus === 'function') active.focus();
            return ok;
        };
        if (navigator.clipboard && window.isSecureContext !== false) {
            return navigator.clipboard.writeText(text).then(() => true, () => legacy());
        }
        return Promise.resolve(legacy());
    }
    function enhance(iface) {
        if (iface.dataset.enhanced) return; iface.dataset.enhanced = '1';
        const samples = samplesFor(iface);
        const row = $('.action-row', iface);
        if (row && samples.length) {
            const b = document.createElement('button'); b.type = 'button'; b.className = 'secondary-btn sample-btn'; b.textContent = '✨ Try sample data';
            b.addEventListener('click', () => {
                samples.forEach(([t, v]) => { t.value = v; });
                const go = $('.primary-btn', row); if (go) go.focus();
                showToast('Sample data loaded. Press Calculate.');
            });
            row.insertBefore(b, $('.secondary-btn', row));
        }
        makeAccessible(iface);
        $$('.result-card', iface).forEach(hookCard);
        $$('.result-card', iface).forEach(card => {
            if (card.querySelector('.copy-btn')) return;
            const c = document.createElement('button'); c.type = 'button'; c.className = 'copy-btn'; c.textContent = '⧉ Copy solution';
            c.addEventListener('click', () => {
                const txt = card.innerText.replace('⧉ Copy solution', '').trim();
                copyText(txt).then(ok => showToast(ok ? 'Solution copied to clipboard' : 'Copy is not available here: select the text and copy it manually'));
            });
            card.appendChild(c);
        });
    }
    const root = $('#interfaceRoot');
    new MutationObserver(() => $$('.stat-interface', root).forEach(enhance)).observe(root, { childList: true, subtree: true });
    $$('.stat-interface', root).forEach(enhance);

    function init() { decorateSidebars(); countTools(); }
    init();
    window.addEventListener('load', init);
    Object.assign(window.StatLabUI, { decodeEntities, sampleFromPlaceholder, copyText });
})();
