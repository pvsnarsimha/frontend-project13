#!/usr/bin/env node
// Rewrites the <script> block of Statistics.html from the files under js/.
// The page uses classic scripts (so it opens from disk), which must be listed in dependency order:
//   core/numerics, core/toolkit, core/charts, core/helpers, core/distributions, core/density, core/stat-charts, core/dist-graphs, core/summary-tests, core/compare-charts, core/feedback   shared foundations
//   tools/<module>/*.js                                      one file per tool, modules in tab order
//   app.js                                                   route table + navigation (needs every tool)
//   ui/navigation, ui/solution, ui/forms, ui/feedback                     presentation layer (each uses what the previous exports)
// Run after adding, renaming or removing a file:  npm run sync:scripts      (a test fails if the page is out of sync)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MODULE_ORDER = ['descriptive', 'preparation', 'probability', 'correlation', 'hypothesis', 'regression'];
const START = '<!-- scripts:start (generated by scripts/sync-script-tags.js) -->';
const END = '<!-- scripts:end -->';

function list(dir) {
    const full = path.join(ROOT, dir);
    return fs.existsSync(full) ? fs.readdirSync(full).filter(f => f.endsWith('.js')).sort().map(f => `${dir}/${f}`) : [];
}

function scriptOrder() {
    const toolModules = fs.readdirSync(path.join(ROOT, 'js/tools')).filter(d => fs.statSync(path.join(ROOT, 'js/tools', d)).isDirectory());
    const unknown = toolModules.filter(m => !MODULE_ORDER.includes(m));
    if (unknown.length) throw new Error('Unknown tool module folder(s): ' + unknown.join(', ') + ' (add them to MODULE_ORDER)');
    return [
        'js/core/numerics.js', 'js/core/toolkit.js', 'js/core/charts.js', 'js/core/helpers.js', 'js/core/distributions.js', 'js/core/density.js', 'js/core/stat-charts.js', 'js/core/dist-graphs.js', 'js/core/summary-tests.js', 'js/core/compare-charts.js', 'js/core/feedback.js',
        ...MODULE_ORDER.flatMap(m => list(`js/tools/${m}`)),
        'js/app.js',
        'js/ui/navigation.js', 'js/ui/solution.js', 'js/ui/forms.js', 'js/ui/feedback.js'   // forms uses what the other two export
    ];
}

function render(order) {
    return START + '\n' + order.map(f => `<script src="${f}"></script>`).join('\n') + '\n' + END;
}

if (require.main === module) {
    const htmlPath = path.join(ROOT, 'Statistics.html');
    let html = fs.readFileSync(htmlPath, 'utf8');
    const block = render(scriptOrder());
    if (html.includes(START)) html = html.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), () => block);
    else html = html.replace(/(<script src="js\/[^"]+"><\/script>\s*)+/, () => block + '\n');
    fs.writeFileSync(htmlPath, html);
    console.log(`Statistics.html: ${scriptOrder().length} script tags`);
}

module.exports = { scriptOrder, render, START, END };
